// Package transport supplies only the raw connection below the existing TLS,
// mTLS, Authelia and Chisel protocol. A carrier cannot select a service target
// or change the enrolled application identity.
package transport

import (
	"context"
	"crypto/tls"
	"errors"
	"net"
	"net/netip"
	"net/url"
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"sync"
	"syscall"

	cfwebsocket "github.com/cloudflare/cloudflared/websocket"
	"github.com/gorilla/websocket"
	"github.com/tailscale/tailcat"
	"tailscale.com/envknob"
	"tailscale.com/tsnet"
)

var privateHost = regexp.MustCompile(`^[a-f0-9]{48}\.taskarian\.invalid$`)
var onionHost = regexp.MustCompile(`^[a-z2-7]{56}\.onion$`)
var quickHost = regexp.MustCompile(`^[a-z0-9]+(?:-[a-z0-9]+)*\.trycloudflare\.com$`)

// ValidHost admits only identities generated by the private enrollment owner.
func ValidHost(host string) bool { return privateHost.MatchString(host) || onionHost.MatchString(host) }

type Descriptor struct {
	Kind    string `json:"kind"`
	Address string `json:"address"`
}

func (d Descriptor) Validate() error {
	switch d.Kind {
	case "cloudflare":
		u, err := url.Parse(d.Address)
		if err == nil && u.Scheme == "https" && quickHost.MatchString(u.Host) && u.User == nil && (u.Path == "" || u.Path == "/") && u.RawPath == "" && u.RawQuery == "" && u.Fragment == "" {
			return nil
		}
	case "tailcat":
		if len(d.Address) > 8192 {
			break
		}
		ci, err := tailcat.ParseAddr(tailcat.Addr(d.Address))
		if err == nil && !ci.ServerPublic.IsZero() && !ci.ServerDiscoPublic.IsZero() && !ci.PresharedKey.IsZero() {
			for _, region := range ci.Region {
				for _, node := range region.Nodes {
					if node.InsecureForTests {
						return errors.New("insecure test DERP nodes are not valid enrollments")
					}
				}
			}
			return nil
		}
	case "tailscale":
		ap, err := netip.ParseAddrPort(d.Address)
		if err == nil && ap.Port() == 443 && ap.String() == d.Address && (netip.MustParsePrefix("100.64.0.0/10").Contains(ap.Addr()) || netip.MustParsePrefix("fd7a:115c:a1e0::/48").Contains(ap.Addr())) {
			return nil
		}
	}
	return errors.New("invalid enrolled transport address")
}

// Status belongs to the private native pipe. A Tailcat address includes its
// upstream WireGuard preshared key and must stay private like the enrollment.
// LoginURL is intended only for native account setup UI.
type Status struct {
	Kind     string `json:"kind"`
	State    string `json:"state"`
	Address  string `json:"address,omitempty"`
	LoginURL string `json:"login_url,omitempty"`
	Error    string `json:"error,omitempty"`
}

// Client owns a single enrollment's independent network node. The platform
// supplies its private persistent tsnet directory; no system daemon is used.
type Client struct {
	d         Descriptor
	tailcat   *tailcat.Client
	tailscale *tsnet.Server
	ctx       context.Context
	cancel    context.CancelFunc
	mu        sync.Mutex
	closed    bool
	active    map[net.Conn]struct{}
}

var configureOnce sync.Once

func configure() {
	configureOnce.Do(func() {
		// This is upstream's supported no-log-upload switch, including tsnet's
		// own logger. Never inherit external provider credentials or control URL.
		envknob.SetNoLogsNoSupport()
		for _, name := range []string{"TS_AUTHKEY", "TS_AUTH_KEY", "TS_CLIENT_SECRET", "TS_CLIENT_ID", "TS_ID_TOKEN", "TS_AUDIENCE"} {
			envknob.Setenv(name, "")
		}
	})
}

func privateDir(dir string) error {
	if !filepath.IsAbs(dir) || filepath.Clean(dir) != dir || strings.ContainsRune(dir, 0) {
		return errors.New("a private native transport state directory is required")
	}
	if err := os.MkdirAll(dir, 0700); err != nil {
		return err
	}
	info, err := os.Lstat(dir)
	if err != nil || !info.IsDir() || info.Mode().Perm()&0077 != 0 {
		return errors.New("transport state directory must be private")
	}
	owner, ok := info.Sys().(*syscall.Stat_t)
	if !ok || owner.Uid != uint32(os.Geteuid()) {
		return errors.New("transport state directory must belong to this user")
	}
	return nil
}

func NewClient(parent context.Context, d Descriptor, dir string) (*Client, error) {
	if err := d.Validate(); err != nil {
		return nil, err
	}
	configure()
	ctx, cancel := context.WithCancel(parent)
	c := &Client{d: d, ctx: ctx, cancel: cancel, active: make(map[net.Conn]struct{})}
	switch d.Kind {
	case "tailcat":
		c.tailcat = &tailcat.Client{Server: tailcat.Addr(d.Address), Logf: func(string, ...any) {}}
	case "tailscale":
		if err := privateDir(dir); err != nil {
			cancel()
			return nil, err
		}
		c.tailscale = newTailscale(dir, "taskarian-client")
		if err := c.tailscale.Start(); err != nil {
			cancel()
			return nil, err
		}
	}
	return c, nil
}

func newTailscale(dir, hostname string) *tsnet.Server {
	return &tsnet.Server{Dir: dir, Hostname: hostname, ControlURL: "https://controlplane.tailscale.com", Logf: func(string, ...any) {}, UserLogf: func(string, ...any) {}}
}

func tailscaleStatus(ctx context.Context, s *tsnet.Server) (Status, error) {
	lc, err := s.LocalClient()
	if err != nil {
		return Status{}, err
	}
	state, err := lc.StatusWithoutPeers(ctx)
	if err != nil {
		return Status{}, err
	}
	result := Status{Kind: "tailscale", State: "starting"}
	switch state.BackendState {
	case "Running":
		result.State = "ready"
		for _, ip := range state.TailscaleIPs {
			if ip.Is4() {
				result.Address = netip.AddrPortFrom(ip, 443).String()
				break
			}
		}
		if result.Address == "" && len(state.TailscaleIPs) > 0 {
			result.Address = netip.AddrPortFrom(state.TailscaleIPs[0], 443).String()
		}
	case "NoState":
		// Upstream is still loading saved state, not requesting a new login.
		result.State = "starting"
	case "NeedsLogin":
		result.State = "login"
	case "NeedsMachineAuth":
		result.State = "approval"
	case "Stopped":
		result.State = "stopped"
	}
	// Only official HTTPS authentication links can be opened by the native UI.
	if u, e := url.Parse(state.AuthURL); e == nil && u.Scheme == "https" && u.Host == "login.tailscale.com" && u.User == nil && u.Fragment == "" {
		result.LoginURL = state.AuthURL
	}
	return result, nil
}

func (c *Client) Status() (Status, error) {
	c.mu.Lock()
	closed := c.closed
	c.mu.Unlock()
	if closed {
		return Status{Kind: c.d.Kind, State: "stopped"}, nil
	}
	if c.tailscale != nil {
		status, err := tailscaleStatus(c.ctx, c.tailscale)
		status.Address = ""
		return status, err
	}
	return Status{Kind: c.d.Kind, State: "ready"}, nil
}

func (c *Client) Dial(ctx context.Context) (net.Conn, error) {
	ctx, cancel := context.WithCancel(ctx)
	stop := context.AfterFunc(c.ctx, cancel)
	defer func() { stop(); cancel() }()
	var conn net.Conn
	var err error
	switch c.d.Kind {
	case "cloudflare":
		// Reuse cloudflared's native access-TCP wire wrapper. Its public carrier
		// helper cannot cancel upgrade and may start an unrelated Access login;
		// only that unavailable dial seam uses Gorilla's context-aware API.
		d := websocket.Dialer{TLSClientConfig: &tls.Config{MinVersion: tls.VersionTLS12}}
		var ws *websocket.Conn
		var stopUpgrade func() bool
		d.NetDialContext = func(ctx context.Context, network, address string) (net.Conn, error) {
			conn, e := (&net.Dialer{}).DialContext(ctx, network, address)
			if e == nil {
				stopUpgrade = context.AfterFunc(ctx, func() { conn.Close() })
			}
			return conn, e
		}
		ws, r, e := d.DialContext(ctx, "wss"+strings.TrimPrefix(c.d.Address, "https"), nil)
		if stopUpgrade != nil {
			stopUpgrade()
		}
		if r != nil && r.Body != nil {
			r.Body.Close()
		}
		err = e
		if err == nil {
			ws.SetReadLimit(512 * 1024)
			conn = &cfwebsocket.GorillaConn{Conn: ws}
		}
	case "tailcat":
		conn, err = c.tailcat.DialTCPPort(ctx, 443)
	case "tailscale":
		conn, err = c.tailscale.Dial(ctx, "tcp", c.d.Address)
	}
	if err != nil {
		return nil, err
	}
	c.mu.Lock()
	if c.closed || ctx.Err() != nil {
		c.mu.Unlock()
		conn.Close()
		return nil, context.Canceled
	}
	t := &ownedConn{Conn: conn, owner: c}
	c.active[t] = struct{}{}
	c.mu.Unlock()
	return t, nil
}

type ownedConn struct {
	net.Conn
	owner *Client
	once  sync.Once
}

func (c *ownedConn) Close() error {
	var err error
	c.once.Do(func() { err = c.Conn.Close(); c.owner.mu.Lock(); delete(c.owner.active, c); c.owner.mu.Unlock() })
	return err
}

func (c *Client) Close() {
	c.mu.Lock()
	if c.closed {
		c.mu.Unlock()
		return
	}
	c.closed = true
	c.cancel()
	conns := make([]net.Conn, 0, len(c.active))
	for conn := range c.active {
		conns = append(conns, conn)
	}
	c.mu.Unlock()
	for _, conn := range conns {
		conn.Close()
	}
	if c.tailcat != nil {
		c.tailcat.Close()
	}
	if c.tailscale != nil {
		c.tailscale.Close()
	}
}
